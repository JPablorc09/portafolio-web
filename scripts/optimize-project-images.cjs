// Optional asset preparation. Normal Angular builds consume the checked-in outputs.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const cwebp = process.argv[2] || process.env.CWEBP_PATH || 'cwebp';
const version = execFileSync(cwebp, ['-version'], { windowsHide: true }).toString().trim();
const source = fs.readFileSync('src/app/data/projects.ts', 'utf8');
const projects = JSON.parse(
  source.slice(source.indexOf('[', source.indexOf('=')), source.lastIndexOf(']') + 1),
);
const publicImages = [
  ...new Set(
    projects
      .filter(
        (project) =>
          project.context !== 'institutional' &&
          ['capture', 'promotional'].includes(project.imageKind),
      )
      .flatMap((project) => [project.image, ...(project.gallery || [])]),
  ),
];
const directory = 'src/assets/images/optimized';
fs.mkdirSync(directory, { recursive: true });
const manifest = {},
  report = [];
for (const image of publicImages) {
  // VendeTico captures are prepared as WebP; keep their reviewed dimensions and variants.
  if (image.startsWith('/assets/images/vendetico/')) {
    const prepared = JSON.parse(fs.readFileSync('docs/vendetico/imagenes.json', 'utf8'))[image];
    if (!prepared || !fs.existsSync(path.join('src', prepared.src)))
      throw Error('Missing prepared VendeTico image: ' + image);
    manifest[image] = prepared;
    continue;
  }
  const file = path.join('src', image);
  const original = fs.readFileSync(file);
  if (original.subarray(1, 4).toString() !== 'PNG') throw Error('Expected a PNG: ' + file);
  const width = original.readUInt32BE(16),
    height = original.readUInt32BE(20);
  const stem = path
    .basename(file, '.png')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/gi, '-')
    .toLowerCase();
  const variants = [];
  for (const size of [...new Set([480, 960, 1600, width].filter((size) => size <= width))].sort(
    (a, b) => a - b,
  )) {
    const temporary = path.join(directory, '.' + stem + '-' + size + '.webp');
    const args = ['-quiet', '-lossless', '-exact', '-m', '6', '-q', '100'];
    if (size !== width) args.push('-resize', String(size), '0');
    execFileSync(cwebp, [...args, file, '-o', temporary], { windowsHide: true });
    const bytes = fs.readFileSync(temporary);
    const digest = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    const name = `${stem}-${size}-${digest}.webp`;
    const target = path.join(directory, name);
    if (fs.existsSync(target)) fs.unlinkSync(temporary);
    else fs.renameSync(temporary, target);
    variants.push({ src: '/assets/images/optimized/' + name, width: size, bytes: bytes.length });
  }
  const full = variants.find((item) => item.width === width);
  manifest[image] = {
    src: full.src,
    width,
    height,
    srcset: variants.map((item) => `${item.src} ${item.width}w`).join(', '),
  };
  report.push({
    source: image,
    width,
    height,
    originalBytes: original.length,
    originalSha256: crypto.createHash('sha256').update(original).digest('hex'),
    fullWebpBytes: full.bytes,
    variants,
  });
  console.log(
    `${path.basename(image)}: ${original.length} -> ${full.bytes} bytes at full resolution`,
  );
}
fs.writeFileSync(
  'src/app/data/optimized-images.ts',
  '/* Generated by scripts/optimize-project-images.cjs. Originals remain untouched. */\nexport const OPTIMIZED_IMAGES: Record<string, { src: string; width: number; height: number; srcset: string }> = ' +
    JSON.stringify(manifest, null, 2) +
    ';\n',
);
fs.mkdirSync('docs/revision-g', { recursive: true });
fs.writeFileSync(
  'docs/revision-g/imagenes.json',
  JSON.stringify(
    {
      encoder: 'cwebp ' + version,
      settings: 'lossless, exact, method 6; resized variants preserve aspect ratio',
      images: report,
    },
    null,
    2,
  ),
);
